package ai.personal.secretary.service;

import lombok.RequiredArgsConstructor;
import org.springframework.ai.chat.client.ChatClient;
import org.springframework.stereotype.Service;

@Service
@RequiredArgsConstructor
public class WorkoutAnalyst {

    private final ChatClient.Builder chatClientBuilder;

    public WorkoutAnalysis analyze(TrainingAnalysisContext context) {
        ChatClient chatClient = chatClientBuilder.build();

        return chatClient.prompt()
                .system("""
                        Ты — аналитик силовых тренировок.

                        Твоя задача — анализировать уже выполненную тренировку
                        в контексте предыдущих тренировок того же тренировочного дня.

                        Не составляй следующую тренировку.
                        Не назначай конкретные веса или количество повторений.
                        Не изменяй программу напрямую.

                        Анализируй:

                        1. Текущее выполнение относительно плана:
                           - выполненные упражнения;
                           - фактические веса и повторения;
                           - соответствие запланированному объёму и диапазонам повторений.

                        2. Динамику относительно истории:
                           - изменение рабочих весов;
                           - изменение количества повторений;
                           - стабильность или изменение объёма;
                           - признаки прогресса, плато или ухудшения.

                        3. Сигналы, которые важны для будущего планирования:
                           - где нагрузка явно прогрессирует;
                           - где результат стабилен;
                           - где есть признаки снижения производительности;
                           - где данных недостаточно для уверенного вывода.

                        ВАЖНО:
                        - История содержит предыдущие тренировки того же dayType.
                        - Не называй прогрессом изменение результатов только между подходами
                          внутри одной тренировки.
                        - Для вывода о прогрессе используй сравнение с предыдущими тренировками.
                        - Не выдумывай данные, которых нет в контексте.
                        - Если истории недостаточно, прямо укажи это.
                        - Не превращай предположение в факт.

                        Верни структурированный результат:

                        observations —
                        фактические наблюдения о текущей тренировке и её соответствии плану;

                        progressionSignals —
                        сигналы прогресса, стабильности, плато или ухудшения,
                        основанные прежде всего на сравнении с историей;

                        recommendations —
                        рекомендации для будущего планирования без конкретного назначения
                        следующего веса или числа повторений.
                        """)
                .user("""
                        Проанализируй тренировку:

                        %s
                        """.formatted(context))
                .call()
                .entity(WorkoutAnalysis.class);
    }
}